"""Dark-mode versions of the figures (featured.* in each page bundle).

    python tools/darkfigs.py                 # all pages; regenerates only what changed
    python tools/darkfigs.py <page folder>   # only these pages, always regenerated (the pull-request bot uses it,
                                             # since a fresh checkout cannot tell from file times what changed)

Each page with a figure gets a `darkFigure` setting in its front matter:
  invert    a dark version is generated as featured-dark-auto.png: brightness is flipped, colours are kept
            (white background -> dark page colour, black lines -> light grey). Good for diagrams and schematics.
  cutout    a dark version is generated by removing only the white background (see-through parts stay
            see-through); colours and lighting are kept. Good for 3D renders on a white background.
  original  dark mode shows the original figure on a light card. For photos and colour maps.
A hand-made featured-dark.png (or .jpg/.webp) in the bundle always wins over both.

Pages without the setting are classified once (diagram-like = mostly white background -> invert) and the
choice is written into their front matter, so it can be reviewed and changed by hand.
"""

import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PAGE_SURFACE = np.array([0x16, 0x1D, 0x1A]) / 255  # --surface in dark mode
MAX_WIDTH = 1600
AUTO = "featured-dark-auto.png"

M1 = np.array([[0.4122214708, 0.5363325363, 0.0514459929], [0.2119034982, 0.6806995451, 0.1073969566],
               [0.0883024619, 0.2817188376, 0.6299787005]])
M2 = np.array([[0.2104542553, 0.7936177850, -0.0040720468], [1.9779984951, -2.4285922050, 0.4505937099],
               [0.0259040371, 0.7827717662, -0.8086757660]])


def to_oklab(rgb):
    lin = np.where(rgb <= 0.04045, rgb / 12.92, ((rgb + 0.055) / 1.055) ** 2.4)
    return np.cbrt(lin @ M1.T) @ M2.T


def from_oklab(lab):
    lin = (lab @ np.linalg.inv(M2).T) ** 3 @ np.linalg.inv(M1).T
    return np.where(lin <= 0.0031308, 12.92 * lin, 1.055 * np.clip(lin, 0, None) ** (1 / 2.4) - 0.055)


def flattened(path):
    """RGB in 0..1 with transparency composited on white, at most MAX_WIDTH wide."""
    im = Image.open(path).convert("RGBA")
    if im.width > MAX_WIDTH:
        im = im.resize((MAX_WIDTH, round(im.height * MAX_WIDTH / im.width)), Image.LANCZOS)
    a = np.asarray(im, dtype=float) / 255
    return a[..., :3] * a[..., 3:] + (1 - a[..., 3:])


def looks_like_diagram(rgb):
    small = np.asarray(Image.fromarray((rgb * 255).astype(np.uint8)).resize((200, 200)), dtype=float) / 255
    return (small.min(-1) > 0.92).mean() >= 0.6  # mostly white background


def invert_brightness(rgb, strength=3.0):
    """Flips brightness, keeps colours. The white background becomes transparent, so the figure blends
    into whatever it sits on (page or card)."""
    lab = to_oklab(rgb)
    surface = to_oklab(PAGE_SURFACE[None, None])[..., 0]
    lab[..., 0] = surface + (1 - lab[..., 0]) * (0.93 - surface)
    colour = np.clip(from_oklab(lab), 0, 1)
    alpha = np.clip((1 - rgb).max(-1) * strength, 0, 1)
    return Image.fromarray((np.dstack([colour, alpha]) * 255).round().astype(np.uint8), "RGBA")


def remove_white(rgb, strength=2.0):
    """White becomes transparent; how opaque a pixel stays depends on how far it is from white."""
    alpha = np.clip((1 - rgb).max(-1) * strength, 0, 1)
    a = np.maximum(alpha[..., None], 1e-3)
    colour = np.clip((rgb - (1 - alpha[..., None])) / a, 0, 1)
    return Image.fromarray((np.dstack([colour, alpha]) * 255).round().astype(np.uint8), "RGBA")


def front_matter(text):
    m = re.match(r"---\n(.*?\n)---\n", text, re.S)
    return m


only = [Path(a).resolve() for a in sys.argv[1:]]
for figure in sorted(ROOT.glob("content/**/featured.*")):
    bundle = figure.parent
    if only and bundle not in only:
        continue
    index = bundle / "index.md"
    text = index.read_text()
    fm = front_matter(text)
    setting = re.search(r"^darkFigure:\s*\"?(\w+)\"?\s*$", fm.group(1), re.M)
    rgb = None
    if setting:
        mode = setting.group(1)
    else:
        rgb = flattened(figure)
        mode = "invert" if looks_like_diagram(rgb) else "original"
        index.write_text(text[:fm.end(1)] + f'darkFigure: "{mode}"\n' + text[fm.end(1):])
    auto = bundle / AUTO
    manual = [p for p in bundle.glob("featured-dark.*")]
    if mode in ("invert", "cutout") and not manual:
        stamp = auto.with_suffix(".mode")
        if (only or not auto.exists() or auto.stat().st_mtime < figure.stat().st_mtime
                or not stamp.exists() or stamp.read_text() != mode):
            rgb = flattened(figure) if rgb is None else rgb
            tmp = auto.with_name("." + auto.name + ".tmp")  # write first, then swap in at once, so a running
            (invert_brightness if mode == "invert" else remove_white)(rgb).save(tmp, "PNG", optimize=True)
            tmp.replace(auto)  # `hugo server` never sees a half-written file
            stamp.write_text(mode)
            print("generated", auto.relative_to(ROOT))
    elif auto.exists():
        auto.unlink()
        auto.with_suffix(".mode").unlink(missing_ok=True)
        print("removed", auto.relative_to(ROOT))
    print(f"{mode:8s} {'(own dark figure) ' if manual else ''}{bundle.relative_to(ROOT / 'content')}")
